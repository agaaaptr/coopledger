-- CoopLedger initial schema

CREATE TABLE members (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_number VARCHAR(32)  NOT NULL UNIQUE,
    full_name     VARCHAR(120) NOT NULL,
    nik           VARCHAR(32),
    phone         VARCHAR(32),
    email         VARCHAR(120),
    address       VARCHAR(255),
    join_date     DATE         NOT NULL DEFAULT CURRENT_DATE,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    member_id     BIGINT       REFERENCES members (id),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE savings_accounts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT        NOT NULL REFERENCES members (id),
    type       VARCHAR(20)   NOT NULL,
    balance    NUMERIC(19,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_savings_member_type UNIQUE (member_id, type)
);

CREATE TABLE transactions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    BIGINT        NOT NULL REFERENCES members (id),
    type         VARCHAR(30)   NOT NULL,
    savings_type VARCHAR(20),
    loan_id      BIGINT,
    amount       NUMERIC(19,2) NOT NULL,
    note         VARCHAR(255),
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE loans (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id            BIGINT        NOT NULL REFERENCES members (id),
    principal            NUMERIC(19,2) NOT NULL,
    interest_rate        NUMERIC(8,4)  NOT NULL,
    term_months          INT           NOT NULL,
    status               VARCHAR(20)   NOT NULL DEFAULT 'APPLIED',
    total_interest       NUMERIC(19,2) NOT NULL DEFAULT 0,
    monthly_installment  NUMERIC(19,2) NOT NULL DEFAULT 0,
    applied_at           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at          TIMESTAMP,
    disbursed_at         TIMESTAMP,
    approved_by          BIGINT        REFERENCES users (id),
    notes                VARCHAR(255)
);

CREATE TABLE installments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id            BIGINT        NOT NULL REFERENCES loans (id),
    installment_number INT           NOT NULL,
    due_date           DATE          NOT NULL,
    amount             NUMERIC(19,2) NOT NULL,
    paid_amount        NUMERIC(19,2) NOT NULL DEFAULT 0,
    status             VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    paid_at            TIMESTAMP,
    CONSTRAINT uq_installment_loan_number UNIQUE (loan_id, installment_number)
);

CREATE INDEX idx_tx_member        ON transactions (member_id);
CREATE INDEX idx_loan_member      ON loans (member_id);
CREATE INDEX idx_installment_loan ON installments (loan_id);
